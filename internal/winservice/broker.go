type VerifiedPrincipal struct {
	sid, logonSID, authenticationID string
	sessionID                       uint32
	verified                        bool
	impersonate                     func(func() error) error
	retain                          func() (VerifiedPrincipal, error)
	release                         func()
	token                           uintptr
	desktopEligible                 bool
	profileID                       string
	logonEpoch                      string
}

func (v VerifiedPrincipal) SID() string              { return v.sid }
func (v VerifiedPrincipal) LogonSID() string         { return v.logonSID }
func (v VerifiedPrincipal) AuthenticationID() string { return v.authenticationID }
func (v VerifiedPrincipal) SessionID() uint32        { return v.sessionID }
func (v VerifiedPrincipal) Verified() bool {
	return v.verified && v.sid != "" && v.logonSID != "" && v.authenticationID != "" && v.sessionID > 0
}
func (v VerifiedPrincipal) WithImpersonation(fn func() error) error {
	if !v.Verified() || v.impersonate == nil {
		return errors.New("verified caller impersonation unavailable")
	}
	return v.impersonate(fn)
}
func (v VerifiedPrincipal) retained() (VerifiedPrincipal, error) {
	if !v.Verified() {
		return v, errors.New("unverified principal")
	}
	if v.retain != nil {
		return v.retain()
	}
	return v, nil
}
func (v VerifiedPrincipal) Close() {
	if v.release != nil {
		v.release()
	}
}

// Binding is generated by the trusted catalog/store, never accepted from RPC.
type Binding struct {
	ProfileID         string    `json:"profile_id"`
	OwnerSID          string    `json:"owner_sid"`
	LogonSID          string    `json:"logon_sid"`
	AuthenticationID  string    `json:"authentication_id"`
	SessionID         uint32    `json:"session_id"`
	ExecutorSID       string    `json:"executor_sid"`
	ServiceInstance   string    `json:"service_instance"`
	Revision          uint64    `json:"revision"`
	RunRef            string    `json:"run_ref,omitempty"`
	Mode              string    `json:"mode,omitempty"`
	Deadline          time.Time `json:"deadline,omitempty"`
	PreparedRunID     string    `json:"prepared_run_id,omitempty"`
	SpecDigest        string    `json:"spec_digest,omitempty"`
	LastRestorationID string    `json:"last_restoration_id,omitempty"`
	ServiceHostPID    int       `json:"service_host_pid,omitempty"`
	ServiceHostBirth  string    `json:"service_host_birth,omitempty"`
	ServiceHostSHA256 string    `json:"service_host_sha256,omitempty"`
	LifecycleSHA256   string    `json:"lifecycle_sha256,omitempty"`
	LogonEpoch        string    `json:"logon_epoch,omitempty"`
	// Derived only from a protected, fully validated rotation intent. Never
	// serialized or accepted as authority from a caller.
	PendingEnrollmentID string `json:"-"`
}
type OwnershipStore interface {
	Lookup(string) (Binding, error)
	Save(Binding) error
	Active() (Binding, bool, error)
}
type Ledger interface {
	Save(p.Operation) error // Durable, secret-free accepted record before ACK.
}
type historicalLedger interface {
	FindOperation(string) (p.Operation, bool, error)
	FindRequest(string, string) (p.Operation, bool, error)
}
type AuthorizedOperation struct {
	principal  VerifiedPrincipal
	binding    Binding
	mutation   p.Mutation
	systemStop bool
	generation uint64
}

func (a AuthorizedOperation) Principal() VerifiedPrincipal { return a.principal }
func (a AuthorizedOperation) Binding() Binding             { return a.binding }
func (a AuthorizedOperation) Mutation() p.Mutation         { return a.mutation }
func (a AuthorizedOperation) ServiceStop() bool            { return a.systemStop }

type PreparedRun struct {
	EngineRunID string
	ExecutorSID string
	SpecDigest  string
	Mode        string
	Deadline    time.Time
}

// BindPreparedRun persists a verified service-created identity before serve.
// Concurrent stop retains the cleanup reference, then denies any later serve.
func (b *Broker) BindPreparedRun(a AuthorizedOperation, prepared PreparedRun) error {
	b.mu.Lock()
	defer b.mu.Unlock()
	current, err := b.owners.Lookup(a.binding.ProfileID)
	if err != nil || authorize(a.principal, current, b.executorSID, b.instance) != nil || current.RunRef != a.binding.RunRef || a.mutation.Kind != p.TakeoverStart {
		return safeError("ACCESS_DENIED")
	}
	if !engineRunID.MatchString(prepared.EngineRunID) || prepared.ExecutorSID != b.executorSID || !digestText.MatchString(prepared.SpecDigest) || prepared.Mode != current.Mode || !prepared.Deadline.Equal(current.Deadline) {
		return safeError("PREPARED_IDENTITY_REJECTED")
	}
	if current.PreparedRunID != "" && (current.PreparedRunID != prepared.EngineRunID || current.SpecDigest != prepared.SpecDigest) {
		return safeError("PREPARED_IDENTITY_REJECTED")
	}
	current.PreparedRunID = prepared.EngineRunID
	current.SpecDigest = prepared.SpecDigest
	if err = b.owners.Save(current); err != nil {
		return safeError("OWNERSHIP_UNAVAILABLE")
	}
	for _, entry := range b.operations {
		if entry.binding.RunRef == current.RunRef {
			entry.binding = current
			entry.operation.RunRef = current.RunRef
		}
	}
	if b.stopping[current.ProfileID] || b.generations[current.ProfileID] != a.generation {
		return context.Canceled
	}
	return nil
}

// Shutdown restores only the independently owned service run, without user
// credentials or a live GUI. It is not exposed as an unauthenticated RPC.
func (b *Broker) Shutdown(ctx context.Context) error {
	b.mu.Lock()
	b.shuttingDown = true
	if backend, ok := b.backend.(interface{ SealForShutdown() }); ok {
		backend.SealForShutdown()
	}
	// A transfer already owns the profile barrier. Let its worker finish before
	// taking a fresh durable snapshot, including any pending publication intent.
	var transferWait <-chan struct{}
	for _, id := range b.attaching {
		if entry := b.operations[id]; entry != nil && entry.pending {
			transferWait = entry.done
		}
	}
	if transferWait != nil {
		b.mu.Unlock()
		select {
		case <-transferWait:
		case <-ctx.Done():
			return ctx.Err()
		}
		b.mu.Lock()
	}
	binding, present, err := b.owners.Active()
	if err != nil {
		b.mu.Unlock()
		return err
	}
	if !present {
		if enrolled, ok := b.owners.(interface{ Enrolled() (Binding, error) }); ok {
			binding, err = enrolled.Enrolled()
			if err != nil {
				b.mu.Unlock()
				return err
			}
		} else {
			b.mu.Unlock()
			return safeError("OWNERSHIP_UNAVAILABLE")
		}
	}
	if binding.ExecutorSID != b.executorSID {
		b.mu.Unlock()
		return safeError("ACCESS_DENIED")
	}
	if binding.PendingEnrollmentID != "" {
		repairer, ok := b.owners.(enrollmentRepairer)
		rotator, canRotate := b.owners.(enrollmentRotator)
		if !ok || !canRotate {
			b.mu.Unlock()
			return safeError("OWNERSHIP_UNAVAILABLE")
		}
		target, repairErr := repairer.PendingTarget(binding)
		if repairErr == nil {
			target, repairErr = rotator.Rotate(binding, target)
		}
		b.mu.Unlock()
		if repairErr != nil {
			return safeError("ENROLLMENT_PERSISTENCE_FAILED")
		}
		if backend, ok := b.backend.(interface {
			EnrollmentRotated(context.Context, Binding) error
		}); ok {
			return backend.EnrollmentRotated(ctx, target)
		}
		return nil
	}
	b.generations[binding.ProfileID]++
	b.stopping[binding.ProfileID] = true
	var wait <-chan struct{}
	if active := b.active[binding.ProfileID]; active != nil && active.run == binding.RunRef {
		active.cancel()
		wait = active.done
	}
	var stopWait <-chan struct{}
	if id := b.stopIDs[binding.ProfileID+"/"+binding.RunRef]; id != "" {
		if previous := b.operations[id]; previous != nil && previous.pending {
			stopWait = previous.done
		}
	}
	b.mu.Unlock()
	if wait != nil {
		select {
		case <-wait:
		case <-ctx.Done():
			return ctx.Err()
		}
	}
	if stopWait != nil {
		select {
		case <-stopWait:
		case <-ctx.Done():
			return ctx.Err()
		}
	}
	// Startup may have published its exact prepared identity while shutdown
	// waited for it to quiesce. Restore that durable identity, not the earlier
	// pre-prepare snapshot.
	b.mu.Lock()
	current, lookupErr := b.owners.Lookup(binding.ProfileID)
	if lookupErr != nil || !sameEnrollment(current, binding) || current.ExecutorSID != b.executorSID || current.ServiceInstance != b.instance {
		b.mu.Unlock()
		return safeError("OWNERSHIP_UNAVAILABLE")
	}
	if binding.RunRef != "" && current.RunRef == "" {
		b.ownedProfile = ""
		b.mu.Unlock()
		return nil
	}
	if current.RunRef != binding.RunRef {
		b.mu.Unlock()
		return safeError("OWNERSHIP_UNAVAILABLE")
	}
	binding = current
	b.mu.Unlock()
	mutation := p.Mutation{Kind: p.TakeoverStop, ProfileID: binding.ProfileID, RunRef: binding.RunRef, ExpectedRevision: binding.Revision, Stop: &p.StopPayload{}}
	outcome, err := b.backend.StopAndRestore(ctx, AuthorizedOperation{binding: binding, mutation: mutation, systemStop: true}, func(Progress) {})
	if err != nil {
		return err
	}
	if !outcome.Restored {
		return safeError("RESTORE_INCOMPLETE")
	}
	b.mu.Lock()
	defer b.mu.Unlock()
	current, err = b.owners.Lookup(binding.ProfileID)
	if err != nil || current.RunRef != binding.RunRef {
		return safeError("OWNERSHIP_UNAVAILABLE")
	}
	clearRunBinding(&current)
	current.LastRestorationID = outcome.RestorationID
	if err = b.owners.Save(current); err != nil {
		return err
	}
	b.ownedProfile = ""
	return nil
}

type Progress struct{ Phase string }
type Completion struct {
	Restored      bool
	Revision      uint64
	RestorationID string
}

type Backend interface {
	Snapshot(context.Context, Binding) (p.Snapshot, error)
	Execute(context.Context, AuthorizedOperation, func(Progress)) (Completion, error)
	StopAndRestore(context.Context, AuthorizedOperation, func(Progress)) (Completion, error)
	Auth(context.Context, AuthorizedOperation, func(Progress)) (Completion, error)
	Workspace(context.Context, VerifiedPrincipal, Binding, p.WorkspacePayload, func(Progress)) (Completion, error)
}

type entry struct {
	operation    p.Operation
	digest       [32]byte
	binding      Binding
	pending      bool
	done         chan struct{}
	attachSource Binding
}
type work struct {
	id         string
	authorized AuthorizedOperation
	generation uint64
	wait       <-chan struct{}
}
type activeWork struct {
	cancel context.CancelFunc
	done   chan struct{}
	run    string
}
type Broker struct {
	ctx                   context.Context
	backend               Backend
	owners                OwnershipStore
	ledger                Ledger
	executorSID, instance string
	mu                    sync.Mutex
	operations            map[string]*entry
	requests              map[string]string
	queue                 chan work
	active                map[string]*activeWork
	generations           map[string]uint64
	stopping              map[string]bool
	stopIDs               map[string]string
	requestDigests        map[string][32]byte
	ownedProfile          string
	shuttingDown          bool
	validationOnly        bool
	serviceHost           platform.Identity
	serviceHostSHA256     string
	lifecycleSHA256       string
	attaching             map[string]string
}

func NewBroker(lifetime context.Context, backend Backend, owners OwnershipStore, ledger Ledger, executorSID, instance string) (*Broker, error) {
	if lifetime == nil || backend == nil || owners == nil || ledger == nil || executorSID == "" || !p.ValidID(instance) {
		return nil, errors.New("complete service-owned dependencies required")
	}
	b := &Broker{ctx: lifetime, backend: backend, owners: owners, ledger: ledger, executorSID: executorSID, instance: instance, operations: map[string]*entry{}, requests: map[string]string{}, queue: make(chan work, 32), active: map[string]*activeWork{}, generations: map[string]uint64{}, stopping: map[string]bool{}, stopIDs: map[string]string{}, requestDigests: map[string][32]byte{}}
	active, present, err := owners.Active()
	if err != nil {
		return nil, err
	}
	if present {
		if active.ExecutorSID != executorSID {
			return nil, errors.New("foreign executor owns active service state")
		}
		b.ownedProfile = active.ProfileID
	}
	go b.loop()
	return b, nil
}
func safeError(code string) *p.Error {
	return &p.Error{Code: code, Message: "The bounded service operation could not be completed."}
}
func newID(prefix string) (string, error) {
	var raw [16]byte
	if _, err := rand.Read(raw[:]); err != nil {
		return "", err
	}
	return prefix + hex.EncodeToString(raw[:]), nil
}
func authorize(v VerifiedPrincipal, binding Binding, executorSID, instance string) error {
	if binding.PendingEnrollmentID != "" || !v.Verified() || !v.desktopEligible || v.profileID != binding.ProfileID || binding.OwnerSID != v.sid || binding.LogonSID != v.logonSID || binding.AuthenticationID != v.authenticationID || binding.SessionID != v.sessionID || (binding.LogonEpoch != "" && binding.LogonEpoch != v.logonEpoch) || binding.ExecutorSID != executorSID || binding.ServiceInstance != instance {
		return safeError("ACCESS_DENIED")
	}
	return nil
}
func (b *Broker) Snapshot(ctx context.Context, v VerifiedPrincipal, profileID string) (p.Snapshot, error) {
	b.mu.Lock()
	binding, err := b.owners.Lookup(profileID)
	transfer := b.attaching[profileID]
	b.mu.Unlock()
	if err != nil || authorize(v, binding, b.executorSID, b.instance) != nil {
		return p.Snapshot{}, safeError("ACCESS_DENIED")
	}
	if transfer != "" {
		return p.Snapshot{ProtocolVersion: p.Version, ServiceState: "attaching", TakeoverState: "restoring", ProfileID: profileID, Revision: binding.Revision, OperationID: transfer, RecoveryRequired: true, Company: p.Channel{State: "unknown", Route: "unknown", IPv6: "unknown"}, Personal: p.Channel{State: "unknown", Route: "unknown", IPv6: "unknown"}}, nil
	}
	var snapshot p.Snapshot
	if backend, ok := b.backend.(interface {
		SnapshotForCaller(context.Context, VerifiedPrincipal, Binding) (p.Snapshot, error)
	}); ok {
		snapshot, err = backend.SnapshotForCaller(ctx, v, binding)
	} else {
		snapshot, err = b.backend.Snapshot(ctx, binding)
	}
	if err != nil {
		return snapshot, err
	}
	b.mu.Lock()
	defer b.mu.Unlock()
	if transfer := b.attaching[profileID]; transfer != "" {
		return p.Snapshot{ProtocolVersion: p.Version, ServiceState: "attaching", TakeoverState: "restoring", ProfileID: profileID, Revision: binding.Revision, OperationID: transfer, RecoveryRequired: true, Company: p.Channel{State: "unknown", Route: "unknown", IPv6: "unknown"}, Personal: p.Channel{State: "unknown", Route: "unknown", IPv6: "unknown"}}, nil
	}
	latest, latestErr := b.owners.Lookup(profileID)
	if latestErr != nil || authorize(v, latest, b.executorSID, b.instance) != nil {
		return p.Snapshot{}, safeError("ACCESS_DENIED")
	}
	if latest.RunRef != binding.RunRef || latest.Revision != binding.Revision {
		snapshot.TakeoverState = "unknown"
		snapshot.Restored = false
		snapshot.RecoveryRequired = true
		snapshot.Company.State = "unknown"
		snapshot.Company.Route = "unknown"
		snapshot.Personal.State = "unknown"
		snapshot.Personal.Route = "unknown"
	}
	var selected *entry
	for _, candidate := range b.operations {
		if candidate.binding.ProfileID != profileID {
			continue
		}
		if candidate.pending && candidate.operation.Kind == p.TakeoverStart {
			selected = candidate
			break
		}
		if selected == nil || candidate.operation.Updated.After(selected.operation.Updated) {
			selected = candidate
		}
	}
	if selected != nil {
		snapshot.OperationID = selected.operation.ID
	}
	return snapshot, nil
}
func (b *Broker) Operation(_ context.Context, v VerifiedPrincipal, id string) (p.Operation, error) {
	b.mu.Lock()
	defer b.mu.Unlock()
	e := b.operations[id]
	var operation p.Operation
	if e == nil {
		if history, ok := b.ledger.(historicalLedger); ok {
			var present bool
			var err error
			operation, present, err = history.FindOperation(id)
			if err != nil || !present {
				return p.Operation{}, safeError("ACCESS_DENIED")
			}
		} else {
			return p.Operation{}, safeError("ACCESS_DENIED")
		}
	} else {
		operation = e.operation
	}
	current, err := b.owners.Lookup(operation.ProfileID)
	if err != nil || (v.profileID != "" && v.profileID != operation.ProfileID) || (e != nil && (e.binding.ProfileID != operation.ProfileID || !samePermanentEnrollment(current, e.binding))) {
		return p.Operation{}, safeError("ACCESS_DENIED")
	}
	// Cached operations retain their original logon tuple as historical data,
	// never as continuing read authority. The current login may inspect its
	// account/profile history; a retired login must fail for both cache paths.
	if authorize(v, current, b.executorSID, b.instance) == nil && b.attaching[operation.ProfileID] == "" {
		return b.resolveAlias(operation)
	}
	// A verified target must be able to follow its own accepted attachment
	// before the old tuple has been restored/rotated, including a failed result.
	// This grants no access to other operations or to a later enrollment.
	if e != nil && operation.Kind == p.AttachEnrollment && sameEnrollment(current, e.attachSource) && authorize(v, e.binding, b.executorSID, b.instance) == nil {
		return operation, nil
	}
	return p.Operation{}, safeError("ACCESS_DENIED")
}
func (b *Broker) Submit(ctx context.Context, v VerifiedPrincipal, m p.Mutation) (p.Operation, error) {
	if err := ctx.Err(); err != nil {
		return p.Operation{}, err
	}
	if err := m.Validate(); err != nil {
		return p.Operation{}, safeError("INVALID_REQUEST")
	}
	raw, _ := json.Marshal(m)
	var ownedMutation p.Mutation
	if json.Unmarshal(raw, &ownedMutation) != nil {
		return p.Operation{}, safeError("INVALID_REQUEST")
	}
	m = ownedMutation
	digest := sha256.Sum256(raw)
	b.mu.Lock()
	defer b.mu.Unlock()
	if b.ctx.Err() != nil || b.shuttingDown {
		return p.Operation{}, safeError("SERVICE_STOPPED")
	}
	binding, err := b.owners.Lookup(m.ProfileID)
	if m.Kind == p.AttachEnrollment {
		return b.submitAttachment(v, m, binding, err)
	}
	if err != nil || authorize(v, binding, b.executorSID, b.instance) != nil {
		return p.Operation{}, safeError("ACCESS_DENIED")
	}
	if b.attaching[m.ProfileID] != "" {
		return p.Operation{}, safeError("LOGIN_TRANSFER_PENDING")
	}
	key := v.sid + "/" + m.ProfileID + "/" + m.RequestID
	if id, ok := b.requests[key]; ok {
		e := b.operations[id]
		if b.requestDigests[key] != digest {
			return p.Operation{}, safeError("REQUEST_ID_CONFLICT")
		}
		return e.operation, nil
	}
	if history, ok := b.ledger.(historicalLedger); ok {
		prior, present, historyErr := history.FindRequest(m.ProfileID, m.RequestID)
		if historyErr != nil {
			return p.Operation{}, safeError("JOURNAL_UNAVAILABLE")
		}
		if present {
			if m.PriorityStop() && prior.Kind == m.Kind && prior.RunRef == m.RunRef {
				return b.resolveAlias(prior)
			}
			return p.Operation{}, safeError("REQUEST_HISTORY_RETAINED")
		}
	}
	b.pruneCompleted()
	if len(b.operations) >= 1024 && !m.PriorityStop() {
		return p.Operation{}, safeError("OPERATION_LIMIT")
	}
	if len(b.operations) >= 1032 && !m.PriorityStop() {
		return p.Operation{}, safeError("PRIORITY_OPERATION_LIMIT")
	}
	if m.ExpectedRevision != binding.Revision && !m.PriorityStop() {
		return p.Operation{}, safeError("REVISION_CONFLICT")
	}
	if m.PriorityStop() && m.ExpectedRevision > binding.Revision {
		return p.Operation{}, safeError("REVISION_CONFLICT")
	}
	if (m.RunRef != "" && m.RunRef != binding.RunRef) || (binding.RunRef != "" && m.RunRef == "" && m.Kind != p.ProfileApply && m.Kind != p.Workspace && m.Kind != p.SettingsApply) {
		return p.Operation{}, safeError("RUN_CONFLICT")
	}
	if m.Kind == p.TakeoverStart && binding.RunRef != "" {
		return p.Operation{}, safeError("RUN_ACTIVE")
	}
	if m.Kind == p.TakeoverStart && b.validationOnly && m.Start.Mode != "validation" {
		return p.Operation{}, safeError("VALIDATION_MODE_REQUIRED")
	}
	if m.Kind == p.TakeoverStart && b.ownedProfile != "" && b.ownedProfile != m.ProfileID {
		return p.Operation{}, safeError("ANOTHER_PROFILE_ACTIVE")
	}
	if b.stopping[m.ProfileID] && !m.PriorityStop() && m.Kind != p.Workspace {
		return p.Operation{}, safeError("RUN_STOPPING")
	}
	stopKey := m.ProfileID + "/" + binding.RunRef
	if m.PriorityStop() {
		if id := b.stopIDs[stopKey]; id != "" {
			previous := b.operations[id]
			prior := previous.operation
			if previous.pending || (prior.Error == nil && prior.Completed && prior.Restored) {
				return b.stopAlias(m, prior)
			}
		}
	}
	if m.PriorityStop() && len(b.operations) >= 1032 {
		return p.Operation{}, safeError("PRIORITY_OPERATION_LIMIT")
	}
	if !m.PriorityStop() && m.Kind != p.AuthRespond && m.Kind != p.AuthCancel && len(b.queue) == cap(b.queue) {
		return p.Operation{}, safeError("BUSY")
	}
	peer, err := v.retained()
	if err != nil {
		return p.Operation{}, safeError("CALLER_TOKEN_UNAVAILABLE")
	}
	id, err := newID("op-")
	if err != nil {
		peer.Close()
		return p.Operation{}, err
	}
	if m.Kind == p.TakeoverStart {
		clearRunBinding(&binding)
		binding.RunRef, err = newID("run-")
		if err != nil {
			peer.Close()
			return p.Operation{}, err
		}
		binding.Mode = m.Start.Mode
		binding.ServiceHostPID = b.serviceHost.PID
		binding.ServiceHostBirth = b.serviceHost.Birth
		binding.ServiceHostSHA256 = b.serviceHostSHA256
		binding.LifecycleSHA256 = b.lifecycleSHA256
		if m.Start.Mode == "validation" {
			binding.Deadline = time.Now().Add(time.Duration(m.Start.ValidationSeconds) * time.Second)
		} else {
			binding.Deadline = time.Time{}
		}
	}
	now := time.Now()
	op := p.Operation{ID: id, RequestID: m.RequestID, ProfileID: m.ProfileID, RunRef: binding.RunRef, Revision: binding.Revision, Kind: m.Kind, Phase: "accepted", Created: now, Updated: now}
	if err := b.ledger.Save(op); err != nil {
		peer.Close()
		return p.Operation{}, safeError("JOURNAL_UNAVAILABLE")
	}
	if err := b.owners.Save(binding); err != nil {
		peer.Close()
		return p.Operation{}, safeError("OWNERSHIP_UNAVAILABLE")
	}
	b.operations[id] = &entry{operation: op, digest: digest, binding: binding, pending: true, done: make(chan struct{})}
	b.requests[key] = id
	b.requestDigests[key] = digest
	w := work{id: id, authorized: AuthorizedOperation{principal: peer, binding: binding, mutation: m, generation: b.generations[m.ProfileID]}, generation: b.generations[m.ProfileID]}
	if m.Kind == p.TakeoverStart {
		b.ownedProfile = m.ProfileID
	}
	if m.PriorityStop() {
		b.generations[m.ProfileID]++
		b.stopping[m.ProfileID] = true
		b.stopIDs[stopKey] = id
		w.generation = b.generations[m.ProfileID]
		if active := b.active[m.ProfileID]; active != nil && active.run == binding.RunRef {
			active.cancel()
			w.wait = active.done
		}
		go b.execute(w, true)
	} else if m.Kind == p.AuthRespond || m.Kind == p.AuthCancel {
		go b.execute(w, false)
	} else {
		b.queue <- w
	}
	return op, nil
}

// Disk journals retain full history. Only completed in-memory entries are
// evicted; their request tombstones prevent an old request from executing anew.
func (b *Broker) pruneCompleted() {
	for len(b.operations) >= 1024 {
		var oldest string
		var at time.Time
		for id, e := range b.operations {
			if e.pending {
				continue
			}
			if oldest == "" || e.operation.Updated.Before(at) {
				oldest = id
				at = e.operation.Updated
			}
		}
		if oldest == "" {
			return
		}
		delete(b.operations, oldest)
		for key, id := range b.requests {
			if id == oldest {
				delete(b.requests, key)
				delete(b.requestDigests, key)
			}
		}
		for key, id := range b.stopIDs {
			if id == oldest {
				delete(b.stopIDs, key)
			}
		}
	}
}
func (b *Broker) loop() {
	defer func() {
		for {
			select {
			case w := <-b.queue:
				b.failWork(w.id, "SERVICE_STOPPED")
				b.finishWork(w.id)
				w.authorized.principal.Close()
			default:
				return
			}
		}
	}()
	for {
		select {
		case <-b.ctx.Done():
			return
		case w := <-b.queue:
			b.execute(w, false)
		}
	}
}
func (b *Broker) execute(w work, stop bool) {
	defer b.finishWork(w.id)
	defer w.authorized.principal.Close()
	ctx, cancel := context.WithCancel(b.ctx)
	defer cancel()
	regular := !stop && w.authorized.mutation.Kind != p.AuthRespond && w.authorized.mutation.Kind != p.AuthCancel && w.authorized.mutation.Kind != p.Workspace
	if stop && w.wait != nil {
		select {
		case <-w.wait:
		case <-b.ctx.Done():
			b.failWork(w.id, "SERVICE_STOPPED")
			return
		}
	}
	b.mu.Lock()
	current, lookupErr := b.owners.Lookup(w.authorized.binding.ProfileID)
	stale := b.ctx.Err() != nil || lookupErr != nil || authorize(w.authorized.principal, current, b.executorSID, b.instance) != nil || current.RunRef != w.authorized.binding.RunRef
	stale = stale || b.attaching[current.ProfileID] != ""
	if !stop {
		stale = stale || current.Revision != w.authorized.mutation.ExpectedRevision || (w.authorized.mutation.Kind != p.Workspace && b.generations[current.ProfileID] != w.generation)
	}
	if stale {
		b.mu.Unlock()
		b.failWork(w.id, "STALE_OPERATION")
		return
	}
	// BindPreparedRun can complete while the priority stop waits. Only the
	// current durable binding authorizes the helper's recovery reference.
	w.authorized.binding = current
	if regular {
		active := &activeWork{cancel: cancel, done: make(chan struct{}), run: current.RunRef}
		b.active[current.ProfileID] = active
		defer func() {
			b.mu.Lock()
			if b.active[current.ProfileID] == active {
				delete(b.active, current.ProfileID)
			}
			close(active.done)
			b.mu.Unlock()
		}()
	}
	b.mu.Unlock()
	progress := func(next Progress) {
		b.mu.Lock()
		defer b.mu.Unlock()
		e := b.operations[w.id]
		if !e.operation.Completed {
			e.operation.Phase = next.Phase
			e.operation.Updated = time.Now()
			if b.ledger.Save(e.operation) != nil {
				setFailure(&e.operation, "JOURNAL_UNAVAILABLE")
			}
		}
	}
	var completion Completion
	var err error
	switch {
	case stop:
		completion, err = b.backend.StopAndRestore(ctx, w.authorized, progress)
	case w.authorized.mutation.Kind == p.AuthRespond || w.authorized.mutation.Kind == p.AuthCancel:
		completion, err = b.backend.Auth(ctx, w.authorized, progress)
	case w.authorized.mutation.Kind == p.Workspace:
		completion, err = b.backend.Workspace(ctx, w.authorized.principal, w.authorized.binding, *w.authorized.mutation.Workspace, progress)
	default:
		completion, err = b.backend.Execute(ctx, w.authorized, progress)
	}
	b.mu.Lock()
	defer b.mu.Unlock()
	e := b.operations[w.id]
	e.operation.Completed = true
	e.operation.Restored = completion.Restored
	e.operation.Updated = time.Now()
	e.operation.Phase = "completed"
	if regular && b.generations[w.authorized.binding.ProfileID] != w.generation {
		err = context.Canceled
	}
	if err != nil {
		setFailure(&e.operation, operationFailureCode(err))
	}
	if stop && !completion.Restored {
		setFailure(&e.operation, "RESTORE_INCOMPLETE")
	}
	if completion.Revision > 0 {
		e.operation.Revision = completion.Revision
	}
	binding, currentErr := b.owners.Lookup(e.binding.ProfileID)
	if currentErr == nil && binding.RunRef == e.binding.RunRef {
		if completion.Revision > 0 {
			binding.Revision = completion.Revision
		}
		if b.owners.Save(binding) != nil {
			setFailure(&e.operation, "OWNERSHIP_UNAVAILABLE")
			e.operation.Completed = false
		}
	} else {
		setFailure(&e.operation, "OWNERSHIP_UNAVAILABLE")
		e.operation.Completed = false
	}
	if e.operation.Error != nil {
		e.operation.Phase = "failed"
	}
	if b.ledger.Save(e.operation) != nil {
		setFailure(&e.operation, "JOURNAL_UNAVAILABLE")
		e.operation.Completed = false
	}
	if stop && completion.Restored && err == nil && e.operation.Error == nil {
		// A failed journal must never discard the durable cleanup reference.
		// Clear it only after the final successful result is durable.
		clearRunBinding(&binding)
		binding.LastRestorationID = completion.RestorationID
		if b.owners.Save(binding) != nil {
			setFailure(&e.operation, "OWNERSHIP_UNAVAILABLE")
			e.operation.Completed = false
			_ = b.ledger.Save(e.operation)
		} else {
			b.stopping[e.binding.ProfileID] = false
			if b.ownedProfile == e.binding.ProfileID {
				b.ownedProfile = ""
			}
		}
	}
}
func (b *Broker) finishWork(id string) {
	b.mu.Lock()
	defer b.mu.Unlock()
	if e := b.operations[id]; e != nil && e.pending {
		e.pending = false
		close(e.done)
	}
}
func clearRunBinding(binding *Binding) {
	binding.RunRef = ""
	binding.Mode = ""
	binding.Deadline = time.Time{}
	binding.PreparedRunID = ""
	binding.SpecDigest = ""
	binding.LastRestorationID = ""
	binding.ServiceHostPID = 0
	binding.ServiceHostBirth = ""
	binding.ServiceHostSHA256 = ""
	binding.LifecycleSHA256 = ""
}
func setFailure(op *p.Operation, code string) {
	op.Phase = "failed"
	if op.FirstFailure == nil {
		op.FirstFailure = safeError(code)
	}
	op.Error = op.FirstFailure
}
func operationFailureCode(err error) string {
	var typed *p.Error
	if errors.As(err, &typed) {
		switch typed.Code {
		case "STOP_REQUIRED", "AUTOCONNECT_UNAVAILABLE", "MANUAL_NODE_SELECTION_UNAVAILABLE", "AUTH_NETWORK_AUTHORIZATION_REQUIRED", "AUTH_RESTART_REQUIRED", "CHALLENGE_CONFLICT", "NO_AUTH_CHALLENGE", "RUNTIME_PREREQUISITES_UNAVAILABLE", "USER_PROFILE_UNAVAILABLE", "PREPARED_IDENTITY_UNAVAILABLE", "RESTORE_PROOF_INCOMPLETE", "EMPTY_STATE_PROOF_UNAVAILABLE", "AUTH_WORKER_EXIT_UNCONFIRMED", "USER_WORKER_EXIT_UNCONFIRMED", "INTENT_APPLY_TIMEOUT", "STOP_BARRIER", "SETTINGS_PERSISTENCE_FAILED":
			return typed.Code
		}
	}
	return "OPERATION_FAILED"
}
func (b *Broker) failWork(id, code string) {
	b.mu.Lock()
	defer b.mu.Unlock()
	e := b.operations[id]
	setFailure(&e.operation, code)
	e.operation.Completed = true
	e.operation.Updated = time.Now()
	if b.ledger.Save(e.operation) != nil {
		setFailure(&e.operation, "JOURNAL_UNAVAILABLE")
		e.operation.Completed = false
	}
}

// MemoryStore is a mock/test adapter. Production hosts must supply their own
// protected, durable ownership catalog and ledger; it is never a default host.
type MemoryStore struct {
	mu            sync.Mutex
	Bindings      map[string]Binding
	Operations    map[string]p.Operation
	RetiredLogins map[string]bool
}

func (m *MemoryStore) Lookup(id string) (Binding, error) {
	m.mu.Lock()
	defer m.mu.Unlock()
	v, ok := m.Bindings[id]
	if !ok {
		return v, errors.New("missing binding")
	}
	return v, nil
}
func (m *MemoryStore) Save(v Binding) error {
	m.mu.Lock()
	defer m.mu.Unlock()
	if m.Bindings == nil {
		m.Bindings = map[string]Binding{}
	}
	m.Bindings[v.ProfileID] = v
	return nil
}
func (m *MemoryStore) Active() (Binding, bool, error) {
	m.mu.Lock()
	defer m.mu.Unlock()
	var result Binding
	found := false
	for _, v := range m.Bindings {
		if v.RunRef != "" {
			if found {
				return result, false, errors.New("multiple active service runs")
			}
			result = v
			found = true
		}
	}
	return result, found, nil
}
func (m *MemoryStore) Enrolled() (Binding, error) {
	m.mu.Lock()
	defer m.mu.Unlock()
	if len(m.Bindings) != 1 {
		return Binding{}, errors.New("one enrolled profile required")
	}
	for _, b := range m.Bindings {
		return b, nil
	}
	return Binding{}, errors.New("no enrolled profile")
}

type MemoryLedger struct {
	mu         sync.Mutex
	Operations map[string]p.Operation
}

func (m *MemoryLedger) Save(v p.Operation) error {
	m.mu.Lock()
	defer m.mu.Unlock()
	if m.Operations == nil {
		m.Operations = map[string]p.Operation{}
	}
	m.Operations[v.ID] = v
	return nil
}
func (m *MemoryLedger) FindOperation(id string) (p.Operation, bool, error) {
	m.mu.Lock()
	defer m.mu.Unlock()
	operation, present := m.Operations[id]
	return operation, present, nil
}
func (m *MemoryLedger) FindRequest(profile, request string) (p.Operation, bool, error) {
	m.mu.Lock()
	defer m.mu.Unlock()
	for _, operation := range m.Operations {
		if operation.ProfileID == profile && operation.RequestID == request {
			return operation, true, nil
		}
	}
	return p.Operation{}, false, nil
}
